from pathlib import Path
import re
import gzip
import hashlib
import json

root = Path(__file__).resolve().parents[1]


def portable_gzip(data):
    # Use the platform-neutral OS byte so Windows/Linux generate identical assets.
    packed = gzip.compress(data, mtime=0)
    return packed[:9] + b"\xff" + packed[10:]

# Source modules concatenate into one cached script: no extra ESP HTTP requests.
modules = ("settings.js", "photos.js", "wifi.js", "maintenance.js")
bundle = "// Generated by tools/embed_web.py; edit web/management/*.js.\n"
bundle += "\n".join((root / "web/management" / name).read_text(encoding="utf8") for name in modules)
(root / "web/management.js").write_text(bundle, encoding="utf8")
html = (root / "web/management.html").read_text(encoding="utf8")
# Strip source indentation without allocating/minifying HTML on the ESP.
html = "\n".join(line.strip() for line in html.splitlines() if line.strip())
# Content-addressed scripts remain cacheable across refreshes and change on edits.
for filename in ("i18n.js", "firmware-bundle.js", "management.js"):
    digest = hashlib.sha256((root / "web" / filename).read_text(encoding="utf8").encode("utf8")).hexdigest()[:16]
    html = re.sub(r"/" + re.escape(filename) + r"\?v=[^\"]+", "/" + filename + "?v=" + digest, html)
assert ')MOSWEB"' not in html
raw = html.encode("utf8")
segments = []
pos = 0
for m in re.finditer(rb"\{\{(token|config|credentials|environment)\}\}", raw):
    segments.append((pos, m.start() - pos, m[1].decode()))
    pos = m.end()
segments.append((pos, len(raw) - pos, ""))
source = (
    '#pragma once\nconst char managementHTML[] PROGMEM = R"MOSWEB('
    + html
    + ')MOSWEB";\n'
)
source += "struct WebSegment {uint32_t offset,length;uint8_t key;};\nconst WebSegment webSegments[] PROGMEM={\n"
source += (
    "\n".join(
        "{%d,%d,%d},"
        % (
            start,
            length,
            {"": 0, "token": 1, "config": 2, "credentials": 3, "environment": 4}[key],
        )
        for start, length, key in segments
    )
    + "\n};\n"
)
(root / "include/webui.h").write_text(source, encoding="utf8")
for filename, symbol in [
    ("access-i18n.js", "accessLocaleJS"),
    ("i18n.js", "localeJS"),
    ("management.js", "managementJS"),
    ("weather-cities.js", "weatherCitiesJS"),
    ("firmware-bundle.js", "firmwareBundleJS"),
    ("setup.js", "setupJS"),
    ("access.js", "accessJS"),
]:
    js = (root / "web" / filename).read_text(encoding="utf8")
    source += "const char " + symbol + '[] PROGMEM = R"MOSJS(' + js + ')MOSJS";\n'
    packed = portable_gzip(js.encode("utf8"))
    source += "const char " + symbol + "Gzip[] PROGMEM = {" + ",".join(str(b) for b in packed) + "};\n"

(root / "include/webui.h").write_text(source, encoding="utf8")

source += (
    'const char accessHTML[] PROGMEM = R"MOSWEB('
    + (root / "web/access.html").read_text(encoding="utf8")
    + ')MOSWEB";\n'
)
(root / "include/webui.h").write_text(source, encoding="utf8")

# Compact flash lookup: custom weather codes use a generic localized title.
cities = json.loads((root / "tools/weather/china-cities.json").read_text(encoding="utf8"))
codes = sorted(int(row[2]) for row in cities)
header = "#pragma once\n#include <Arduino.h>\nnamespace WeatherLocations {\n"
header += "const uint32_t cityCodes[] PROGMEM={" + ",".join(map(str,codes)) + "};\n"
header += "inline bool listed(const String& code){uint32_t value=strtoul(code.c_str(),nullptr,10);int low=0,high=sizeof(cityCodes)/sizeof(cityCodes[0])-1;while(low<=high){int mid=(low+high)/2;uint32_t item=pgm_read_dword(cityCodes+mid);if(item==value)return true;if(item<value)low=mid+1;else high=mid-1;}return false;}\n}\n"
(root / "include/weather_locations.h").write_text(header,encoding="utf8")
